/**
 * Returns a localized Question object (falling back to canonical English if untranslated).
 * Guaranteed to NEVER mutate the canonical dataset or branch IDs.
 */
export function getLocalizedQuestion(question: Question, language: Language): Question {
  if (language !== 'ar') return question;
  const translation = ARABIC_QUESTIONS[question.id];
  if (!translation) return question;

  const localizedAnswers: AnswerOption[] = question.answers.map((ans) => {
    const ansTrans = translation.answers[ans.id];
    if (!ansTrans) return ans;
    return {
      ...ans,
      text: ansTrans.text,
      consequence_summary: ansTrans.consequence_summary,
      learning_point: ansTrans.learning_point,
    };
  });

  return {
    ...question,
    story: translation.story || question.story,
    question: translation.question || question.question,
    answers: localizedAnswers,
  };
}

/**
 * Returns a localized MissionEnding object (falling back to canonical English if untranslated).
 * Guaranteed to NEVER mutate canonical scores or IDs.
 */
export function getLocalizedEnding(ending: MissionEnding, language: Language): MissionEnding {
  if (language !== 'ar') return ending;
  const translation = ARABIC_ENDINGS[ending.id];
  if (!translation) return ending;

  return {
    ...ending,
    title: translation.title || ending.title,
    description: translation.description || ending.description,
    scientific_explanation: translation.scientific_explanation || ending.scientific_explanation,
    learning_point: translation.learning_point || ending.learning_point,
  };
}
